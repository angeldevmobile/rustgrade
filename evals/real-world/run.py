#!/usr/bin/env python3
"""Runs rustgrade over the crates in crates.txt and prints a Markdown report.

Usage (from the repo root, after `cargo build --release`):

    python evals/real-world/run.py > evals/real-world/RESULTS.md
    python evals/real-world/run.py --bin rustgrade   # an installed binary

Crates are downloaded once from crates.io into target/real-world/. Standard
library only, so it runs anywhere Python 3.9+ does.
"""

import argparse
import collections
import io
import json
import subprocess
import sys
import tarfile
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
CACHE = ROOT / "target" / "real-world"
USER_AGENT = "rustgrade-real-world-eval (https://github.com/angeldevmobile/rustgrade)"
SEVERITIES = ["critical", "high", "medium", "low", "info"]


def read_crates():
    for line in (HERE / "crates.txt").read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#"):
            name, version = line.split()
            yield name, version


def fetch(name, version):
    """Returns the unpacked crate directory, downloading it if needed."""
    dest = CACHE / f"{name}-{version}"
    if dest.is_dir():
        return dest
    url = f"https://static.crates.io/crates/{name}/{name}-{version}.crate"
    req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(req) as resp:
        data = resp.read()
    CACHE.mkdir(parents=True, exist_ok=True)
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as tar:
        for member in tar.getmembers():
            if member.name.startswith(("/", "..")) or ".." in Path(member.name).parts:
                raise ValueError(f"unsafe path in {url}: {member.name}")
        tar.extractall(CACHE)
    return dest


def rustgrade(binary, args):
    out = subprocess.run([binary, *args, "--format", "json"], capture_output=True, text=True)
    if out.returncode not in (0, 1):
        raise RuntimeError(f"rustgrade {' '.join(args)} failed:\n{out.stderr}")
    return json.loads(out.stdout)


def per_1k(n, lines):
    return f"{1000 * n / max(lines, 1):.1f}"


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    exe = "rustgrade.exe" if sys.platform == "win32" else "rustgrade"
    parser.add_argument("--bin", default=str(ROOT / "target" / "release" / exe))
    parser.add_argument("--top", type=int, default=3, help="rules listed per crate")
    args = parser.parse_args()

    version = subprocess.run([args.bin, "--version"], capture_output=True, text=True)
    rows, totals, grades = [], collections.Counter(), collections.Counter()
    by_rule = collections.Counter()
    for name, ver in read_crates():
        print(f"scanning {name} {ver}...", file=sys.stderr)
        crate = fetch(name, ver)
        audit = rustgrade(args.bin, ["audit", str(crate), "--no-clippy", "--no-tests"])
        findings = audit["scan"]["findings"]
        sev = collections.Counter(f["severity"] for f in findings)
        rules = collections.Counter(f["rule"] for f in findings)
        lines = audit["code_lines"]  # what the rubric divides by
        totals.update(sev)
        totals["lines"] += lines
        grades[audit["grade"]] += 1
        by_rule.update(rules)
        rows.append((f"{name} {ver}", lines, sev, len(findings), audit, rules))

    out = []
    out.append("# rustgrade on real crates\n")
    out.append(f"Generated by `evals/real-world/run.py` with `{version.stdout.strip()}`.")
    out.append("Scanner only (`audit --no-clippy --no-tests`), so grades reflect rustgrade's")
    out.append("rules alone. Code lines exclude blanks, comments and tests, as the rubric")
    out.append("counts them.\n")
    out.append("**Grades:** " + ", ".join(f"{grades[g]} {g}" for g in "ABCDF" if grades[g]) + ".\n")
    out.append(
        "| Crate | Code lines | Critical | High | Medium | Low"
        " | Findings per 1k | Highs per 1k | Grade | Top rules |"
    )
    out.append("|---|---:|---:|---:|---:|---:|---:|---:|---|---|")
    for crate, lines, sev, total, audit, rules in rows:
        cap = f" ({audit['cap']})" if audit.get("cap") else ""
        top = ", ".join(f"{r} {n}" for r, n in rules.most_common(args.top))
        out.append(
            f"| {crate} | {lines} | {sev['critical']} | {sev['high']} | {sev['medium']}"
            f" | {sev['low']} | {per_1k(total, lines)} | {per_1k(sev['high'], lines)}"
            f" | {audit['grade']} {audit['score']}{cap} | {top} |"
        )
    total = sum(totals[s] for s in SEVERITIES)
    out.append(
        f"| **total** | {totals['lines']} | {totals['critical']} | {totals['high']}"
        f" | {totals['medium']} | {totals['low']} | {per_1k(total, totals['lines'])}"
        f" | {per_1k(totals['high'], totals['lines'])} | | |"
    )
    out.append("\n## By rule\n")
    out.append("| Rule | Findings |")
    out.append("|---|---:|")
    out.extend(f"| `{rule}` | {n} |" for rule, n in by_rule.most_common())
    print("\n".join(out))


if __name__ == "__main__":
    main()
